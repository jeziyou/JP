/**
 * Add Chinese meaning to vocabulary word
 * @param word The Japanese word
 * @param existingMeaning The existing (English or other) meaning
 * @returns Meaning with Chinese translation appended
 */
export function addChineseMeaning(word: string, existingMeaning: string): string {
  if (!word || !existingMeaning) return existingMeaning || '';
  const chinese = translations[word];
  if (chinese && !existingMeaning.includes(chinese) && existingMeaning !== chinese) {
    const sep = existingMeaning.endsWith('；') || existingMeaning.endsWith(';') ? ' ' : '；';
    return `${existingMeaning}${sep}${chinese}`;
  }
  return existingMeaning;
}

/**
 * Get Chinese meaning for a word
 * @param word The Japanese word
 * @returns Chinese meaning or empty string if not found
 */
export function getChineseMeaning(word: string): string {
  return translations[word] || '';
}

/**
 * Build a complete meaning string: English + Chinese
 * @param word The Japanese word
 * @param englishMeaning The English meaning
 * @returns Meaning string with Chinese translation, or just english if not found
 */
export function buildMeaning(word: string, englishMeaning: string): string {
  if (!englishMeaning) return englishMeaning || '';
  const cn = translations[word];
  if (!cn) return englishMeaning;
  // Check if already contains Chinese (from reading-data)
  if (englishMeaning.includes(cn)) return englishMeaning;
  // Check if already has Chinese characters
  if (/[\u4e00-\u9faf]/.test(englishMeaning)) return englishMeaning;
  return `${englishMeaning} / ${cn}`;
}

/**
 * Get all translations for a word list, returns map
 */
export function getTranslationsFor(words: string[]): Record<string, string> {
  const result: Record<string, string> = {};
  for (const w of words) {
    if (translations[w]) result[w] = translations[w];
  }
  return result;
}
